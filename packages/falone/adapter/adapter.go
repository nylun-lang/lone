package adapter

import (
	"fmt"
	"strings"
)

// AdapterKind represents the runtime environment for the JavaScript glue code.
type AdapterKind string

const (
	AdapterNode    AdapterKind = "node"
	AdapterBrowser AdapterKind = "browser"
)

// ParseAdapterKind validates and normalizes an adapter kind string.
func ParseAdapterKind(s string) (AdapterKind, error) {
	switch strings.ToLower(strings.TrimSpace(s)) {
	case "node", "nodejs":
		return AdapterNode, nil
	case "browser", "web", "dom":
		return AdapterBrowser, nil
	default:
		return "", fmt.Errorf("invalid adapter kind %q: expected 'node' or 'browser'", s)
	}
}

// GenerateAdapter produces JavaScript runtime glue code for the specified target environment.
func GenerateAdapter(kind AdapterKind, wasmFileName string) (string, error) {
	if wasmFileName == "" {
		wasmFileName = "module.wasm"
	}

	switch kind {
	case AdapterNode:
		return generateNodeAdapter(wasmFileName), nil
	case AdapterBrowser:
		return generateBrowserAdapter(wasmFileName), nil
	default:
		return "", fmt.Errorf("unsupported adapter kind %q", kind)
	}
}

func generateNodeAdapter(wasmFileName string) string {
	return fmt.Sprintf(`// Falone WebAssembly Runtime Adapter (Node.js)
// Auto-generated by Falone Compiler for web target

const fs = require("node:fs");
const path = require("node:path");

const decoder = new TextDecoder("utf-8");

/**
 * Creates the 'env' import object providing runtime intrinsics like #print.
 * @param {Function} getMemory - Function returning the WebAssembly.Memory instance.
 * @param {Object} [hooks={}] - Optional custom hook overrides.
 */
function createEnv(getMemory, hooks = {}) {
  return {
    print(ptr, len) {
      const memory = getMemory();
      if (!memory) return;
      const bytes = new Uint8Array(memory.buffer, ptr, len);
      const text = decoder.decode(bytes);
      if (hooks.print) {
        hooks.print(text);
      } else {
        process.stdout.write(text);
      }
    },
    ...hooks.extraEnv,
  };
}

/**
 * Instantiates the WebAssembly module with Falone runtime glue.
 * @param {string|Buffer|Uint8Array|ArrayBuffer} wasmInput - File path or binary buffer.
 * @param {Object} [options={}] - Custom instantiation options.
 */
async function instantiate(wasmInput, options = {}) {
  let wasmBytes;
  if (typeof wasmInput === "string") {
    wasmBytes = fs.readFileSync(wasmInput);
  } else if (Buffer.isBuffer(wasmInput) || wasmInput instanceof Uint8Array || wasmInput instanceof ArrayBuffer) {
    wasmBytes = wasmInput;
  } else {
    throw new TypeError("Expected wasmInput to be a file path string or Buffer/Uint8Array");
  }

  let instance;
  const importObject = {
    env: createEnv(() => instance.exports.memory, options.hooks),
    ...options.imports,
  };

  const result = await WebAssembly.instantiate(wasmBytes, importObject);
  instance = result.instance || result;
  return instance;
}

/**
 * Instantiates and invokes the module entry point (main or _start).
 * @param {string|Buffer|Uint8Array|ArrayBuffer} wasmInput - File path or binary buffer.
 * @param {Object} [options={}] - Custom options.
 */
async function run(wasmInput, options = {}) {
  const instance = await instantiate(wasmInput, options);
  const entry = instance.exports.main || instance.exports._start;
  if (typeof entry === "function") {
    return entry();
  }
  throw new Error("No exported main or _start function found in WebAssembly module");
}

// Direct CLI invocation: node <adapter.js> [path/to/module.wasm]
if (require.main === module) {
  const wasmPath = process.argv[2] || path.join(__dirname, %q);
  run(wasmPath).catch(err => {
    console.error("Falone runtime error:", err);
    process.exit(1);
  });
}

module.exports = { instantiate, run, createEnv };
`, wasmFileName)
}

func generateBrowserAdapter(wasmFileName string) string {
	return fmt.Sprintf(`// Falone WebAssembly Runtime Adapter (Browser)
// Auto-generated by Falone Compiler for web target

const decoder = new TextDecoder("utf-8");

/**
 * Creates the 'env' import object providing runtime intrinsics like #print.
 * @param {Function} getMemory - Function returning the WebAssembly.Memory instance.
 * @param {Object} [hooks={}] - Optional custom hook overrides (e.g. redirecting print).
 */
export function createEnv(getMemory, hooks = {}) {
  return {
    print(ptr, len) {
      const memory = getMemory();
      if (!memory) return;
      const bytes = new Uint8Array(memory.buffer, ptr, len);
      const text = decoder.decode(bytes);
      if (hooks.print) {
        hooks.print(text);
      } else {
        console.log(text);
      }
    },
    ...hooks.extraEnv,
  };
}

/**
 * Instantiates the WebAssembly module with Falone runtime glue in browser environments.
 * @param {string|URL|Response|ArrayBuffer|Uint8Array} wasmSource - URL string, fetch Response, or binary buffer.
 * @param {Object} [options={}] - Custom instantiation options.
 */
export async function instantiate(wasmSource, options = {}) {
  let instance;
  const importObject = {
    env: createEnv(() => instance.exports.memory, options.hooks),
    ...options.imports,
  };

  let result;
  if (typeof wasmSource === "string" || wasmSource instanceof URL) {
    if (typeof WebAssembly.instantiateStreaming === "function") {
      result = await WebAssembly.instantiateStreaming(fetch(wasmSource), importObject);
    } else {
      const response = await fetch(wasmSource);
      const bytes = await response.arrayBuffer();
      result = await WebAssembly.instantiate(bytes, importObject);
    }
  } else if (wasmSource instanceof Response) {
    result = await WebAssembly.instantiateStreaming(wasmSource, importObject);
  } else if (wasmSource instanceof ArrayBuffer || wasmSource instanceof Uint8Array) {
    result = await WebAssembly.instantiate(wasmSource, importObject);
  } else {
    throw new TypeError("Expected wasmSource to be a URL string, Response, ArrayBuffer, or Uint8Array");
  }

  instance = result.instance || result;
  return instance;
}

/**
 * Instantiates and invokes the module entry point (main or _start).
 * @param {string|URL|Response|ArrayBuffer|Uint8Array} wasmSource - WebAssembly source.
 * @param {Object} [options={}] - Custom options.
 */
export async function run(wasmSource = %q, options = {}) {
  const instance = await instantiate(wasmSource, options);
  const entry = instance.exports.main || instance.exports._start;
  if (typeof entry === "function") {
    return entry();
  }
  throw new Error("No exported main or _start function found in WebAssembly module");
}

export default { instantiate, run, createEnv };
`, wasmFileName)
}
